"""E39 tables, generated from the continuous Dyna loop's logs -> results/moba/dream/DYNA_LIVE_TABLE.md.
Sources (results/moba/dream/): <run>_eval.jsonl (60 games per side on the fixed seeds 50000000+ after every PPO update),
<run>_fresh.jsonl (300 per side on seeds 60000000+, candidates only), dyna_live_fresh_check.txt / dyna_live_holdout.txt
(300 per side on 60000000+ / 70000000+), abl_*_eval.jsonl, dyna_live_state.json (resets, anchor), dyna_live_meta/
(the collector's games). usage: python scripts/moba/dyna_live_table.py"""
import json, re, statistics as stat
from pathlib import Path

D = Path("results/moba/dream")
out = ["# Continuous Dyna loop (E39): generated tables", "",
       "Generated by `scripts/moba/dyna_live_table.py`. Wins are radiant games won against the shipped net; dire is 0 in every row.", ""]


def rows(f):
    return [json.loads(l) for l in (D / f).read_text().splitlines() if l.strip()] if (D / f).exists() else []


def seed_file(f):
    res = {}
    for l in (D / f).read_text().splitlines():
        m = re.match(r"RESULT (\S+) radiant (\d+)/(\d+) wins towers ([\d.]+)", l)
        if m:
            res[m[1]] = (int(m[2]), int(m[3]), float(m[4]))
    return res


out += ["## 1. Fresh and holdout seeds (300 games per side)", "",
        "| policy | fresh 60000000+ (used to pick anchors) | holdout 70000000+ (never used) | towers/game (holdout) |", "|---|---|---|---|"]
fresh, hold = seed_file("dyna_live_fresh_check.txt"), seed_file("dyna_live_holdout.txt")
fr4 = {f"ppol4_u{r['update']}": r["radiant_wins"] for r in rows("ppol4_fresh.jsonl")}
for name, label in (("u0017", "u0017 (start, E38)"), ("ppol_u51", "ppol u51"), ("ppol_u71", "ppol u71"), ("ppol4_u10", "ppol4 u10 (anchor 12:47)"), ("ppol4_u49", "ppol4 u49 (anchor 13:23)")):
    f = fresh[name][0] if name in fresh else fr4.get(name)
    h = hold.get(name)
    out.append(f"| {label} | {f'{f}/300 ({100 * f / 300:.0f}%)' if f is not None else '-'} | "
               f"{f'{h[0]}/{h[1]} ({100 * h[0] / h[1]:.0f}%)' if h else '-'} | {h[2] if h else '-'} |")
out += ["", "Standard error of a 300-game win rate near 50%: about 2.9 points (8.7 games).", ""]

out += ["## 2. Every PPO run of the loop (fixed seeds, 60 games per side after each update)", "",
        "| run | setting | updates evaluated | radiant wins: mean / min / max | points with <= 8 wins | drift resets |", "|---|---|---|---|---|---|"]
st = json.loads((D / "dyna_live_state.json").read_text())
resets = {"ppol": st.get("resets_ppol", []), "ppol2": st.get("resets_ppol2", []), "ppol3": [], "ppol4": st.get("resets", [])}
setting = {"ppol": "lr 3e-4, death penalty on, no KL", "ppol2": "lr 5e-5, death penalty on, no KL",
           "ppol3": "lr 5e-5, death penalty 0, KL 1.0 to anchor", "ppol4": "lr 5e-5, death penalty 0, KL 0.3 to anchor"}
for run in ("ppol", "ppol2", "ppol3", "ppol4"):
    r = [x for x in rows(f"{run}_eval.jsonl") if x.get("update", 0) > 0 and "radiant_wins" in x]
    w = [x["radiant_wins"] for x in r]
    if w:
        out.append(f"| {run} | {setting[run]} | {len(w)} | {stat.mean(w):.1f} / {min(w)} / {max(w)} | {sum(v <= 8 for v in w)} | {len(resets[run])} |")
out += [""]

out += ["## 3. Ablation (all from ppol u71, lr 5e-5, frozen WM wml @3600, no resets)", "",
        "| arm | pods | radiant wins by update | towers | kills | deaths | game length |", "|---|---|---|---|---|---|---|"]
for arm, pods in (("abl_ent0", 3), ("abl_death0", 3), ("abl_kl", 2)):
    r = rows(f"{arm}_eval.jsonl")
    if r:
        l = r[-1]
        out.append(f"| {arm} | {pods} | " + " → ".join(f"u{x['update']}:{x['radiant_wins']}" for x in r)
                   + f" | {l['radiant_towers_ours']} | {l['radiant_kills']} | {l['radiant_deaths']} | {l['radiant_ticks']:.0f} |")
out += ["", "Last four columns: the arm's last evaluated update.", ""]

out += ["## 4. Anchor changes (ppol4)", "", "| candidate update | fixed-seed wins | fresh wins | anchor before (fresh) | became anchor |",
        "|---|---|---|---|---|"]
for r in rows("ppol4_fresh.jsonl"):
    out.append(f"| {r['update']} | {r['fixed']} | {r['radiant_wins']}/300 | u{r['anchor']} ({r['anchor_fresh']}) | "
               f"{'yes' if r['radiant_wins'] >= r['anchor_fresh'] + 9 else 'no'} |")
out += [""]

meta = [g for f in sorted((D / "dyna_live_meta").glob("*.json")) for g in json.loads(f.read_text())]
out += ["## 5. Collector", "", f"{len(meta)} real games of the current PPO policy vs the shipped net, recorded + verified, "
        f"in {len(list((D / 'dyna_live_meta').glob('*.json')))} files of 10 (`s3://puffertank/moba/runs/dyna_live/`).", ""]
(D / "DYNA_LIVE_TABLE.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
